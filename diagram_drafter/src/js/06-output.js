/* =========================================================================
 * Output: Sheet -> SVG markup (grouped by owner) and Sheet -> DXF (R2013).
 * ========================================================================= */

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const n4 = (v) => +v.toFixed(4);

function svgPathD(pts, closed, Y) {
  let d = `M${n4(pts[0][0])} ${Y(pts[0][1])}`;
  const n = pts.length;
  const segs = closed ? n : n - 1;
  for (let i = 0; i < segs; i++) {
    const [xa, ya, bulge] = pts[i], [xb, yb] = pts[(i + 1) % n];
    if (Math.abs(bulge || 0) < 1e-9) { d += `L${n4(xb)} ${Y(yb)}`; continue; }
    const theta = 4 * Math.atan(Math.abs(bulge));
    const chord = Math.hypot(xb - xa, yb - ya);
    if (chord < 1e-9) continue;
    const r = chord / (2 * Math.sin(theta / 2));
    // DXF positive bulge = CCW (y up) -> SVG sweep-flag 0 after the y flip
    d += `A${n4(r)} ${n4(r)} 0 ${theta > Math.PI ? 1 : 0} ${bulge > 0 ? 0 : 1} ${n4(xb)} ${Y(yb)}`;
  }
  return closed ? d + "Z" : d;
}

/**
 * SVG markup for a sheet. Entities are grouped per owner as
 * <g data-owner="id">; `minStroke` keeps hairlines visible on screen.
 */
function sheetToSvgContent(sh, { minStroke = 0 } = {}) {
  const Y = (y) => n4(SHEET_H - y);
  const groups = new Map();
  const add = (owner, s) => { if (!groups.has(owner)) groups.set(owner, []); groups.get(owner).push(s); };
  const stroke = (layer) => {
    const [color, lw, dashed] = LAYERS[layer] || [7, 25];
    const w = Math.max(Math.max(lw, 9) / 100 / 25.4, minStroke);
    return `stroke="${ACI_RGB[color] || "#000"}" stroke-width="${n4(w)}"${dashed ? ' stroke-dasharray="0.125 0.0625"' : ""}`;
  };
  for (const e of sh.ents) {
    const col = ACI_RGB[(LAYERS[e.layer] || [7])[0]] || "#000";
    if (e.t === "line") {
      add(e.owner, `<line x1="${n4(e.x0)}" y1="${Y(e.y0)}" x2="${n4(e.x1)}" y2="${Y(e.y1)}" ${stroke(e.layer)}/>`);
    } else if (e.t === "circle") {
      add(e.owner, `<circle cx="${n4(e.x)}" cy="${Y(e.y)}" r="${n4(e.r)}" fill="none" ${stroke(e.layer)}/>`);
    } else if (e.t === "poly") {
      add(e.owner, `<path d="${svgPathD(e.pts, e.closed, Y)}" fill="none" ${stroke(e.layer)}/>`);
    } else if (e.t === "fill") {
      add(e.owner, `<path d="${svgPathD(e.pts, true, Y)}" fill="${col}" stroke="none"/>`);
    } else if (e.t === "text") {
      const [v, hz] = e.align;
      const base = v === "M" ? e.y - e.h / 2 : v === "T" ? e.y - e.h : e.y;
      const anchor = hz === "L" ? "start" : hz === "R" ? "end" : "middle";
      add(e.owner, `<text x="${n4(e.x)}" y="${Y(base)}" font-size="${n4(e.h / sh.font.cap)}" text-anchor="${anchor}"` +
        `${e.bold ? ' font-weight="bold"' : ""} fill="${col}">${esc(e.s)}</text>`);
    }
  }
  let out = "";
  for (const [owner, items] of groups) out += `<g data-owner="${esc(owner)}">${items.join("")}</g>`;
  return out;
}

function sheetToSvg(sh, { width = "100%", height = "100%", minStroke = 0 } = {}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SHEET_W} ${SHEET_H}" width="${width}" height="${height}" ` +
         `font-family="${sh.font.css.replace(/"/g, "'")}" stroke-linecap="round" stroke-linejoin="round">` +
         `<rect width="${SHEET_W}" height="${SHEET_H}" fill="#fff"/>${sheetToSvgContent(sh, { minStroke })}</svg>`;
}

// ---------------------------------------------------------------------- DXF
/**
 * Splice the entities into the embedded R2013 template (generated by
 * tools/make_dxf_template.py: header, layers, text styles, ANSI B layout).
 */
function sheetToDxf(sh) {
  const tpl = JSON.parse(document.getElementById("dxf-template").textContent);
  let handle = parseInt(tpl.seed, 16);
  const out = [];
  const tag = (code, value) => out.push(String(code).padStart(3, " "), String(value));
  const num = (v) => {
    let s = String(+v.toFixed(6));
    if (s === "-0") s = "0";
    return s.includes(".") || s.includes("e") ? s : s + ".0";
  };
  const head = (type, layer, sub, color) => {
    tag(0, type); tag(5, (handle++).toString(16).toUpperCase()); tag(330, tpl.owner);
    tag(100, "AcDbEntity"); tag(8, layer);
    if (color !== undefined) tag(62, color);
    tag(100, sub);
  };
  const ALIGN_H = { L: 0, C: 1, R: 2 }, ALIGN_V = { B: 1, M: 2, T: 3 };

  for (const e of sh.ents) {
    if (e.t === "line") {
      head("LINE", e.layer, "AcDbLine");
      tag(10, num(e.x0)); tag(20, num(e.y0)); tag(30, "0.0");
      tag(11, num(e.x1)); tag(21, num(e.y1)); tag(31, "0.0");
    } else if (e.t === "poly") {
      head("LWPOLYLINE", e.layer, "AcDbPolyline");
      tag(90, e.pts.length); tag(70, e.closed ? 1 : 0);
      for (const [x, y, b] of e.pts) {
        tag(10, num(x)); tag(20, num(y));
        if (b) tag(42, num(b));
      }
    } else if (e.t === "circle") {
      head("CIRCLE", e.layer, "AcDbCircle");
      tag(10, num(e.x)); tag(20, num(e.y)); tag(30, "0.0"); tag(40, num(e.r));
    } else if (e.t === "text") {
      head("TEXT", e.layer, "AcDbText");
      tag(10, num(e.x)); tag(20, num(e.y)); tag(30, "0.0"); tag(40, num(e.h));
      tag(1, e.s.replace(/%%/g, "%%%")); tag(7, e.bold ? "DD-BOLD" : "DD-STD");
      const hz = ALIGN_H[e.align[1]];
      if (hz) tag(72, hz);
      tag(11, num(e.x)); tag(21, num(e.y)); tag(31, "0.0");
      tag(100, "AcDbText"); tag(73, ALIGN_V[e.align[0]]);
    } else if (e.t === "fill") {
      const bulges = e.pts.some((p) => p[2]);
      head("HATCH", e.layer, "AcDbHatch", LAYERS[e.layer][0]);
      tag(10, "0.0"); tag(20, "0.0"); tag(30, "0.0");
      tag(210, "0.0"); tag(220, "0.0"); tag(230, "1.0");
      tag(2, "SOLID"); tag(70, 1); tag(71, 0);
      tag(91, 1); tag(92, 3); tag(72, bulges ? 1 : 0); tag(73, 1); tag(93, e.pts.length);
      for (const [x, y, b] of e.pts) {
        tag(10, num(x)); tag(20, num(y));
        if (bulges) tag(42, num(b || 0));
      }
      tag(97, 0); tag(75, 1); tag(76, 1); tag(98, 0);
    }
  }
  const [reg, bold] = sh.font.files;
  return tpl.dxf
    .replace("\n  3\narial.ttf\n", () => `\n  3\n${reg}\n`)
    .replace("\n  3\narialbd.ttf\n", () => `\n  3\n${bold}\n`)
    .replace("%%ENTITIES%%", () => (out.length ? out.join("\n") + "\n" : ""))
    .replace("%%HANDSEED%%", () => handle.toString(16).toUpperCase());
}
